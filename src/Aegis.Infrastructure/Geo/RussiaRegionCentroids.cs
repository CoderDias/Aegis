    public static IReadOnlyList<(string Name, (double Lat, double Lng) Centroid)> MatchRegions(string text)
    {
        if (string.IsNullOrWhiteSpace(text))
        {
            return [];
        }

        var matches = new List<(string Name, (double Lat, double Lng) Centroid)>();
        foreach (var (name, centroid) in ByName)
        {
            if (text.Contains(name, StringComparison.OrdinalIgnoreCase))
            {
                matches.Add((name, centroid));
            }
        }

        return matches;
    }
